// Backup completo do PEPMH: estrutura do banco (schema.sql), dados de todas as tabelas (JSON),
// contas de login (auth.users) e todos os arquivos do Storage, num .zip guardado no bucket privado "backups".
// Chamada só com a chave de uso único em private.backup_keys (validade curta). Devolve um link assinado (7 dias).
import postgres from "npm:postgres@3.4.4";
import { zipSync, strToU8 } from "npm:fflate@0.8.2";

const SB = Deno.env.get("SUPABASE_URL")!, SRK = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
const H = { apikey: SRK, Authorization: `Bearer ${SRK}` };

const SCHEMA_SQL = `
with
ext as (select string_agg(format('create extension if not exists %I;', extname), E'\\n' order by extname) s from pg_extension where extname not in ('plpgsql')),
tabs as (
  select string_agg(format(E'create table if not exists public.%I (\\n%s\\n);', c.relname,
    (select string_agg(format('  %I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
        case when a.attidentity <> '' then ' generated by default as identity' when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end,
        case when a.attnotnull then ' not null' else '' end), E',\\n' order by a.attnum)
       from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
      where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped)), E'\\n\\n' order by c.relname) s
  from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind = 'r'),
cons as (
  select string_agg(format('alter table public.%I add constraint %I %s;', c.relname, k.conname, pg_get_constraintdef(k.oid)), E'\\n'
           order by case k.contype when 'p' then 0 when 'u' then 1 when 'c' then 2 else 3 end, c.relname) s
  from pg_constraint k join pg_class c on c.oid = k.conrelid where c.relnamespace = 'public'::regnamespace and k.contype in ('p','u','c','f','x')),
idx as (
  select string_agg(i.indexdef || ';', E'\\n' order by i.tablename, i.indexname) s from pg_indexes i
   where i.schemaname = 'public' and not exists (select 1 from pg_constraint k where k.conname = i.indexname)),
vw as (select string_agg(format(E'create or replace view public.%I as\\n%s', viewname, definition), E'\\n\\n') s from pg_views where schemaname = 'public'),
fn as (
  select string_agg(pg_get_functiondef(p.oid) || ';', E'\\n\\n' order by p.proname) s from pg_proc p
   where p.pronamespace = 'public'::regnamespace and p.prokind in ('f','p')
     and not exists (select 1 from pg_depend dp where dp.objid = p.oid and dp.deptype = 'e')),
rls as (
  select string_agg(format('alter table public.%I enable row level security;', relname), E'\\n' order by relname) s
  from pg_class where relnamespace = 'public'::regnamespace and relkind = 'r' and relrowsecurity),
pol as (
  select string_agg(format('create policy %I on %I.%I as %s for %s to %s%s%s;', policyname, schemaname, tablename, permissive, cmd,
      array_to_string(roles, ', '), coalesce(' using (' || qual || ')', ''), coalesce(' with check (' || with_check || ')', '')), E'\\n' order by schemaname, tablename, policyname) s
  from pg_policies where schemaname in ('public', 'storage')),
trg as (
  select string_agg(pg_get_triggerdef(t.oid) || ';', E'\\n' order by c.relname, t.tgname) s
  from pg_trigger t join pg_class c on c.oid = t.tgrelid
  where not t.tgisinternal and (c.relnamespace = 'public'::regnamespace or (c.relnamespace = 'auth'::regnamespace and c.relname = 'users'))),
grt as (
  select string_agg(format('grant %s on public.%I to %I;', privilege_type, table_name, grantee), E'\\n' order by table_name, grantee, privilege_type) s
  from information_schema.role_table_grants where table_schema = 'public' and grantee in ('anon', 'authenticated')),
bk as (select string_agg(format('insert into storage.buckets (id, name, public) values (%L, %L, %s) on conflict (id) do nothing;', id, name, public), E'\\n') s from storage.buckets where id <> 'backups'),
cr as (select string_agg(format('select cron.schedule(%L, %L, %L);', jobname, schedule, command), E'\\n') s from cron.job)
select concat_ws(E'\\n\\n',
  '-- PEPMH · estrutura do banco gerada em ' || to_char(now() at time zone 'America/Sao_Paulo', 'DD/MM/YYYY HH24:MI') || ' (horário de Brasília)',
  '-- Ordem para restaurar num projeto Supabase novo: este arquivo inteiro e depois os dados de dados/*.json.',
  '-- 1. Extensões', ext.s, '-- 2. Tabelas', tabs.s, '-- 3. Chaves, únicos, checagens e chaves estrangeiras', cons.s, '-- 4. Índices', idx.s,
  '-- 5. Funções', fn.s, '-- 6. Visões', vw.s, '-- 7. Segurança por linha (RLS) e políticas', rls.s, pol.s, '-- 8. Gatilhos', trg.s,
  '-- 9. Permissões', grt.s, '-- 10. Buckets do Storage', bk.s, '-- 11. Tarefas agendadas (pg_cron)', cr.s) as ddl
from ext, tabs, cons, idx, vw, fn, rls, pol, trg, grt, bk, cr`;

Deno.serve(async (req) => {
  const sql = postgres(Deno.env.get("SUPABASE_DB_URL")!, { prepare: false, max: 1 });
  try {
    const key = req.headers.get("x-backup-key") || "";
    const ok = key ? await sql`delete from private.backup_keys where key = ${key} and expires_at > now() returning 1` : [];
    if (!ok.length) return new Response("forbidden", { status: 403 });

    const now = new Date(), stamp = new Date(now.getTime() - 3 * 3600e3).toISOString().slice(0, 16).replace("T", "_").replace(":", "h");
    const files: Record<string, Uint8Array> = {};
    const counts: Record<string, number> = {};

    files["estrutura/schema.sql"] = strToU8((await sql.unsafe(SCHEMA_SQL))[0].ddl);

    const tables = await sql`select tablename from pg_tables where schemaname = 'public' order by 1`;
    for (const { tablename } of tables) {
      const [{ j }] = await sql.unsafe(`select coalesce(json_agg(t), '[]'::json) j from public."${tablename.replace(/"/g, '""')}" t`);
      files[`dados/${tablename}.json`] = strToU8(JSON.stringify(j, null, 1)); counts[tablename] = j.length;
    }
    const [{ j: users }] = await sql`select coalesce(json_agg(u), '[]'::json) j from (select id, email, phone, encrypted_password, email_confirmed_at, phone_confirmed_at,
      raw_app_meta_data, raw_user_meta_data, created_at, updated_at, last_sign_in_at, banned_until, is_anonymous from auth.users order by created_at) u`;
    files["contas/auth_users.json"] = strToU8(JSON.stringify(users, null, 1)); counts["auth.users"] = users.length;

    const objs = await sql`select bucket_id, name, metadata from storage.objects where bucket_id <> 'backups' order by bucket_id, name`;
    files["arquivos/_lista.json"] = strToU8(JSON.stringify(objs, null, 1));
    let nArq = 0; const falhas: string[] = [];
    for (const o of objs) {
      const r = await fetch(`${SB}/storage/v1/object/${o.bucket_id}/${o.name.split("/").map(encodeURIComponent).join("/")}`, { headers: H });
      if (!r.ok) { falhas.push(`${o.bucket_id}/${o.name} (${r.status})`); continue; }
      files[`arquivos/${o.bucket_id}/${o.name}`] = new Uint8Array(await r.arrayBuffer()); nArq++;
    }

    files["LEIA-ME.txt"] = strToU8([
      `Backup do PEPMH · ${stamp.replace("_", " às ")} (horário de Brasília)`, "",
      "estrutura/schema.sql   tabelas, chaves, índices, funções, gatilhos, políticas de acesso (RLS), buckets e tarefas agendadas",
      "dados/*.json           todos os registros de cada tabela do sistema",
      "contas/auth_users.json contas de login (e-mail e senha criptografada) — guarde em local seguro",
      "arquivos/              exames, comprovantes, documentos assinados e demais anexos, nas mesmas pastas do Storage", "",
      "Registros por tabela:", ...Object.entries(counts).map(([t, n]) => `  ${t}: ${n}`), "",
      `Arquivos do Storage: ${nArq} de ${objs.length}` + (falhas.length ? `\nNão baixados: ${falhas.join(", ")}` : ""), "",
      "O código do sistema fica no GitHub (rlambaia2023-a11y/odontocerto, branch pepmh) e no arquivo de código enviado junto com este backup.",
      "ATENÇÃO: contém dados de saúde de pacientes (LGPD). Não compartilhe e guarde em local protegido.",
    ].join("\n"));

    const zip = zipSync(files, { level: 6 });
    await fetch(`${SB}/storage/v1/bucket`, { method: "POST", headers: { ...H, "Content-Type": "application/json" }, body: JSON.stringify({ id: "backups", name: "backups", public: false }) });
    const path = `pepmh-backup-${stamp}.zip`;
    const up = await fetch(`${SB}/storage/v1/object/backups/${path}`, { method: "POST", headers: { ...H, "Content-Type": "application/zip", "x-upsert": "true" }, body: zip });
    if (!up.ok) throw new Error("upload: " + up.status + " " + await up.text());
    const sg = await (await fetch(`${SB}/storage/v1/object/sign/backups/${path}`, { method: "POST", headers: { ...H, "Content-Type": "application/json" }, body: JSON.stringify({ expiresIn: 7 * 86400 }) })).json();
    const url = SB + "/storage/v1" + (sg.signedURL || sg.signedUrl);
    return Response.json({ ok: true, path, bytes: zip.length, arquivos: nArq, arquivos_total: objs.length, falhas, counts, url });
  } catch (e) {
    return Response.json({ ok: false, error: String(e) }, { status: 500 });
  } finally { await sql.end(); }
});
